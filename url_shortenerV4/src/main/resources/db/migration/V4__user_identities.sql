-- Accounts at Google or GitHub linked to a user. A user can have several,
-- as well as a password. provider_user_id is the provider's stable id for
-- the account (Google "sub", GitHub numeric id), never the email.
CREATE TABLE user_identities (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider         VARCHAR(20)  NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    email            VARCHAR(255),
    created_date     TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_user_identities_provider_account UNIQUE (provider, provider_user_id)
);

CREATE INDEX idx_user_identities_user ON user_identities (user_id);
