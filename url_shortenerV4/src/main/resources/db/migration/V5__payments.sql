-- Payments for Monthly / Yearly plans, made through Razorpay. A row is created
-- with each Razorpay order and marked PAID once Razorpay confirms it.
CREATE TABLE payments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    plan                VARCHAR(20)  NOT NULL,
    amount_paise        INTEGER      NOT NULL,
    currency            VARCHAR(3)   NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    razorpay_order_id   VARCHAR(64)  NOT NULL,
    razorpay_payment_id VARCHAR(64),
    -- The paid period's end after this payment was applied.
    period_end_after    TIMESTAMP(6),
    created_date        TIMESTAMP(6) NOT NULL,
    paid_date           TIMESTAMP(6),
    CONSTRAINT uk_payments_razorpay_order UNIQUE (razorpay_order_id)
);

CREATE INDEX idx_payments_user ON payments (user_id, created_date DESC);

-- Payment reminder emails already sent, so each is sent once per paid period.
CREATE TABLE payment_reminders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    period_end TIMESTAMP(6) NOT NULL,
    kind       VARCHAR(30)  NOT NULL,
    sent_date  TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_payment_reminders_once UNIQUE (user_id, period_end, kind)
);
